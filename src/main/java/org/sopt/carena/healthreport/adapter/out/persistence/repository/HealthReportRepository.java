package org.sopt.carena.healthreport.adapter.out.persistence.repository;

import java.time.LocalDate;
import java.util.List;
import java.util.Optional;

import org.sopt.carena.healthreport.adapter.out.persistence.entity.HealthReportEntity;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Slice;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;

public interface HealthReportRepository extends JpaRepository<HealthReportEntity, Long> {

	Optional<HealthReportEntity> findByMemberEntityIdAndId(long memberId, long healthReportId);

	Optional<HealthReportEntity> findTopByMemberEntityIdOrderByHealthCheckDateDesc(long memberId);

	boolean existsByMemberEntityIdAndHealthCheckDate(Long memberId, LocalDate healthCheckDate);

	boolean existsByMemberEntityIdAndHealthCheckDateAfter(long memberId, LocalDate healthCheckDate);

	Slice<HealthReportEntity> findAllByMemberEntityIdOrderByHealthCheckDateDesc(long memberId, Pageable pageable);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndHeightIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndWeightIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndWaistCircumferenceIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndBmiIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndSystolicBpIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndDiastolicBpIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndHemoglobinIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndFastingGlucoseIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndAstIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndAltIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndGammaGtpIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndSerumCreatinineIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	List<HealthReportEntity> findTop5ByMemberEntityIdAndEgfrIsNotNullAndHealthCheckDateLessThanEqualOrderByHealthCheckDateDesc(long memberId, LocalDate healthCheckDate);

	@Modifying
	@Query("DELETE FROM HealthReportEntity h WHERE h.memberEntity.id = :memberId")
	void deleteAllByMemberEntityId(Long memberId);
}
